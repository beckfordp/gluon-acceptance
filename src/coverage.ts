/**
 * Traceability (ACC-6.1): which of gluon's `docs/user-stories.md` tasks the
 * suite accepts, via each scenario's `@US-N.M` tags, and which are out of
 * scope. Pure: the CLI (`scripts/coverage-matrix.ts`) does the file I/O.
 */

/** One `- [x] US-N.M: title` line; `done` is false for `- [ ]`. */
export interface StoryTask {
  id: string
  title: string
  done: boolean
}

/** A scenario, titled `Feature › Scenario`, with its own and its feature's `US-N.M` tags. */
export interface TaggedScenario {
  title: string
  tags: string[]
}

export type CoverageStatus =
  | { kind: 'covered'; scenarios: string[] }
  | { kind: 'out-of-scope'; reason: string }
  | { kind: 'missing' }
  | { kind: 'not-built' };

export interface MatrixRow {
  task: StoryTask
  status: CoverageStatus
}

export interface Matrix {
  rows: MatrixRow[]
  /** Gaps and inconsistencies; the matrix is only complete when empty. */
  problems: string[]
}

// Top-level only: indented lines are notes, not tasks.
const TASK_LINE = /^- \[([ x])\] (US-\d+\.\d+): (.*)$/;
const US_TAG = /^@(US-\d+\.\d+)$/;

export function parseStoryTasks(markdown: string): StoryTask[] {
  return markdown.split('\n').flatMap((line) => {
    const match = TASK_LINE.exec(line);
    if (match === null) return [];
    const [, mark, id, rest] = match;
    // "title — done 2026-10-28 (...)" / "title — **superseded ...": the status note isn't
    // part of the title, but a title may itself contain " — ".
    const title = rest.replace(/ — (done |\*\*).*$/, '').trim();
    return [{ id, title, done: mark === 'x' }];
  });
}

export function parseFeature(text: string): TaggedScenario[] {
  const scenarios: TaggedScenario[] = [];
  let featureName = '';
  let featureTags: string[] = [];
  let pending: string[] = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line.startsWith('@')) {
      pending.push(...line.split(/\s+/).flatMap((tag) => US_TAG.exec(tag)?.slice(1) ?? []));
      continue;
    }
    const keyword = /^(Feature|Scenario Outline|Scenario|Background|Examples):\s*(.*)$/.exec(line);
    if (keyword === null) continue;
    const [, kind, name] = keyword;
    if (kind === 'Feature') {
      featureName = name;
      featureTags = pending;
    } else if (kind === 'Scenario' || kind === 'Scenario Outline') {
      scenarios.push({ title: `${featureName} › ${name}`, tags: [...featureTags, ...pending] });
    }
    pending = [];
  }
  return scenarios;
}

export function buildMatrix(
  tasks: readonly StoryTask[],
  scenarios: readonly TaggedScenario[],
  outOfScope: Readonly<Record<string, string>>,
): Matrix {
  const problems: string[] = [];
  const byId = new Map(tasks.map((task) => [task.id, task]));
  const coveredBy = (id: string): string[] =>
    scenarios.filter((s) => s.tags.includes(id)).map((s) => s.title);

  const rows = tasks.map((task): MatrixRow => {
    if (!task.done) return { task, status: { kind: 'not-built' } };
    const covering = coveredBy(task.id);
    const reason = outOfScope[task.id];
    if (reason !== undefined) {
      if (covering.length > 0) {
        problems.push(`${task.id} is out of scope but also covered by: ${covering.join('; ')}`);
      }
      return { task, status: { kind: 'out-of-scope', reason } };
    }
    if (covering.length > 0) return { task, status: { kind: 'covered', scenarios: covering } };
    problems.push(`${task.id} is done but has no scenario and isn't out of scope`);
    return { task, status: { kind: 'missing' } };
  });

  for (const id of Object.keys(outOfScope)) {
    if (!byId.has(id)) problems.push(`${id} is listed out of scope but isn't in user-stories.md`);
  }
  for (const scenario of scenarios) {
    for (const tag of scenario.tags) {
      const task = byId.get(tag);
      if (task === undefined) problems.push(`${scenario.title} tags ${tag}, which isn't in user-stories.md`);
      else if (!task.done) problems.push(`${scenario.title} tags ${tag}, which isn't built yet`);
    }
  }
  return { rows, problems };
}

const STATUS_LABELS: Record<CoverageStatus['kind'], string> = {
  'covered': 'covered',
  'out-of-scope': 'out of scope',
  'missing': '**missing**',
  'not-built': 'not built',
};

function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function detail(status: CoverageStatus): string {
  switch (status.kind) {
    case 'covered': return status.scenarios.join('<br>');
    case 'out-of-scope': return status.reason;
    default: return '';
  }
}

export function renderMatrix({ rows, problems }: Matrix): string {
  const count = (kind: CoverageStatus['kind']) => rows.filter((r) => r.status.kind === kind).length;
  return [
    '# Acceptance coverage matrix',
    '',
    'Generated by `npm run coverage:matrix` from gluon `docs/user-stories.md` and `features/`.',
    '',
    `Covered: ${count('covered')} · Out of scope: ${count('out-of-scope')} · `
      + `Missing: ${count('missing')} · Not built: ${count('not-built')}`,
    '',
    '| Task | Title | Status | Scenarios / reason |',
    '|---|---|---|---|',
    ...rows.map(({ task, status }) =>
      `| ${task.id} | ${cell(task.title)} | ${STATUS_LABELS[status.kind]} | ${cell(detail(status))} |`),
    '',
    '## Problems',
    '',
    ...(problems.length === 0
      ? ['No problems: every done task is covered or out of scope.']
      : problems.map((p) => `- ${p}`)),
    '',
  ].join('\n');
}
